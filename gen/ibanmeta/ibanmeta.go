// Package ibanmeta provides functionality to generate Go code for the IBAN country registry
// from the official SWIFT IBAN registry CSV file.
// It reads the CSV file and generates a Go map containing country-specific IBAN metadata.
package ibanmeta

import (
	"encoding/csv"
	"os"
)

// GenerateRegistry reads the CSV and returns the Go code for the registry as []byte.
func GenerateRegistry(csvPath string) ([]byte, error) {
	f, err := os.Open(csvPath)
	if err != nil {
		return nil, err
	}
	r := csv.NewReader(f)
	records, err := r.ReadAll()
	if err != nil {
		return nil, err
	}
	out := "// Code generated by go:generate; DO NOT EDIT.\n"
	out += "package countrymeta\n\n"
	out += "type Meta struct {\n\tCountry string\n\tLength int\n\tRegex string\n\tBankStart int\n\tBankEnd int\n\tAccountStart int\n\tAccountEnd int\n}\n"
	out += "var Registry = map[string]Meta{\n"
	for _, rec := range records[1:] {
		country := rec[0]
		length := rec[1]
		regex := rec[2]
		bankStart := rec[3]
		bankEnd := rec[4]
		acctStart := rec[5]
		acctEnd := rec[6]
		out += "\t\"" + country + "\": {Country: \"" + country + "\", Length: " + length + ", Regex: `" + regex + "`, BankStart: " + bankStart + ", BankEnd: " + bankEnd + ", AccountStart: " + acctStart + ", AccountEnd: " + acctEnd + "},\n"
	}
	out += "}\n"
	return []byte(out), nil
}
