// gen_iban_meta.go: Generate Go country registry from SWIFT IBAN Registry CSV
package main

import (
	"encoding/csv"
	"os"
)

func main() {
	f, err := os.Open("iban_registry.csv") // Downloaded from SWIFT
	if err != nil {
		panic(err)
	}
	defer func() {
		if cerr := f.Close(); cerr != nil {
			panic(cerr)
		}
	}()
	r := csv.NewReader(f)
	records, err := r.ReadAll()
	if err != nil {
		panic(err)
	}
	if _, err := os.Stdout.WriteString("// Code generated by go:generate; DO NOT EDIT.\n"); err != nil {
		panic(err)
	}
	if _, err := os.Stdout.WriteString("package countrymeta\n\n"); err != nil {
		panic(err)
	}
	if _, err := os.Stdout.WriteString("type Meta struct {\n\tCountry string\n\tLength int\n\tRegex string\n\tBankStart int\n\tBankEnd int\n\tAccountStart int\n\tAccountEnd int\n}\n"); err != nil {
		panic(err)
	}
	if _, err := os.Stdout.WriteString("var Registry = map[string]Meta{\n"); err != nil {
		panic(err)
	}
	for _, rec := range records[1:] { // skip header
		country := rec[0]
		length := rec[1]
		regex := rec[2]
		bankStart := rec[3]
		bankEnd := rec[4]
		acctStart := rec[5]
		acctEnd := rec[6]
		if _, err := os.Stdout.WriteString("\t\"" + country + "\": {Country: \"" + country + "\", Length: " + length + ", Regex: `" + regex + "`, BankStart: " + bankStart + ", BankEnd: " + bankEnd + ", AccountStart: " + acctStart + ", AccountEnd: " + acctEnd + "},\n"); err != nil {
			panic(err)
		}
	}
	if _, err := os.Stdout.WriteString("}\n"); err != nil {
		panic(err)
	}
}
